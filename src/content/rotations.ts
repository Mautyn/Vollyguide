import { rotateClockwise } from '../domain/rotation';
import type { Rotation, ZoneMap } from '../domain/types';
import { ZONES } from '../domain/zones';
import {
  BASE_5_1_ROTATION_1,
  BASE_SPOTS,
  type Formation,
  type FormationPlayer,
} from './formations';

/**
 * Rotations in the order a team plays them. A rotation is named after the zone the
 * setter stands in, and each clockwise rotation moves the setter from zone 1 to 6, 5, ...
 */
export const ROTATION_ORDER: readonly Rotation[] = [1, 6, 5, 4, 3, 2];

export function nextRotation(rotation: Rotation): Rotation {
  const index = ROTATION_ORDER.indexOf(rotation);
  return ROTATION_ORDER[(index + 1) % ROTATION_ORDER.length]!;
}

export function previousRotation(rotation: Rotation): Rotation {
  const index = ROTATION_ORDER.indexOf(rotation);
  return ROTATION_ORDER[(index - 1 + ROTATION_ORDER.length) % ROTATION_ORDER.length]!;
}

/** 5-1 base positions for a rotation, generated by rotating rotation 1 clockwise. */
function buildBaseRotation(rotation: Rotation): Formation {
  const start = BASE_5_1_ROTATION_1.players;
  let assignment = Object.fromEntries(start.map((p) => [p.zone, p])) as ZoneMap<FormationPlayer>;
  for (let step = 0; step < ROTATION_ORDER.indexOf(rotation); step++) {
    assignment = rotateClockwise(assignment);
  }

  const players = ZONES.map((zone) => ({
    ...assignment[zone],
    zone,
    position: { ...BASE_SPOTS[zone] },
  }));
  // Keep the roster order of rotation 1 so the player list doesn't reshuffle.
  players.sort(
    (a, b) => start.findIndex((p) => p.id === a.id) - start.findIndex((p) => p.id === b.id),
  );

  return { id: `5-1-r${rotation}-base`, system: '5-1', rotation, phase: 'base', players };
}

export const BASE_5_1_ROTATIONS: Readonly<Record<Rotation, Formation>> = {
  1: buildBaseRotation(1),
  2: buildBaseRotation(2),
  3: buildBaseRotation(3),
  4: buildBaseRotation(4),
  5: buildBaseRotation(5),
  6: buildBaseRotation(6),
};
